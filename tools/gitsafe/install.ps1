# gitsafe installer -- install a pre-commit hook that blocks secrets
#
# 用法（任意 git 仓库，任选一种）：
#   pwsh -File "D:\Deepseek Work\tmp\gitsafe\install.ps1"
#   pwsh -File "D:\Deepseek Work\tmp\gitsafe\install.ps1" -Repo "D:\code\my-proj"

param(
    [string]$Repo = ".",
    [switch]$Force
)

$ErrorActionPreference = "Stop"

function Say([string]$t, [string]$c = "Gray") {
    Write-Host $t -ForegroundColor $c
}

# ---- 1. locate repo ----
$root = (& git -C $Repo rev-parse --show-toplevel 2>$null)
if ($LASTEXITCODE -ne 0 -or -not $root) {
    Say "[X] $Repo 不是 git 仓库。先 git init，或用 -Repo 指定路径。" "Red"
    exit 1
}
$root = "$root".Trim()
Say "[i] 仓库根目录: $root" "Cyan"

# ---- 2. locate python ----
$py = $null
foreach ($cand in @("python", "py", "python3")) {
    $c = Get-Command $cand -ErrorAction SilentlyContinue
    if ($c) { $py = $c.Source; break }
}
if (-not $py) {
    Say "[X] 找不到 python，钩子无法运行。" "Red"
    exit 1
}
Say "[i] python: $py"

# ---- 3. install hook ----
$hooksDir = Join-Path $root ".git\hooks"
New-Item -ItemType Directory -Force -Path $hooksDir | Out-Null

$srcScanner = Join-Path $PSScriptRoot "pre-commit.py"
if (-not (Test-Path $srcScanner)) {
    Say "[X] 缺少 $srcScanner" "Red"
    exit 1
}
$dstScanner = Join-Path $hooksDir "gitsafe_precommit.py"
Copy-Item -Force $srcScanner $dstScanner

$pyPathFile = Join-Path $hooksDir "gitsafe_python.txt"
Set-Content -Path $pyPathFile -Value $py -Encoding utf8 -NoNewline

$hookPath = Join-Path $hooksDir "pre-commit"
if (Test-Path $hookPath) {
    $old = Get-Content $hookPath -Raw
    if ($old -notmatch "gitsafe") {
        if (-not $Force) {
            $bak = "$hookPath.bak-" + (Get-Date -Format "yyyyMMddHHmmss")
            Copy-Item $hookPath $bak
            Say "[!] 已有 pre-commit，已备份: $bak" "Yellow"
        }
    }
}

$hookLines = @(
    '#!/bin/sh',
    '# gitsafe pre-commit hook -- generated by install.ps1',
    'HOOK_DIR="$(cd "$(dirname "$0")" && pwd)"',
    'PY="$(cat "$HOOK_DIR/gitsafe_python.txt" 2>/dev/null)"',
    'if [ -z "$PY" ] || [ ! -x "$PY" ]; then PY=python; fi',
    '"$PY" "$HOOK_DIR/gitsafe_precommit.py"',
    'exit $?'
)
$hookBody = ($hookLines -join "`n") + "`n"
[System.IO.File]::WriteAllText($hookPath, $hookBody, (New-Object System.Text.UTF8Encoding $false))
Say "[OK] hook 已安装: $hookPath" "Green"

# ---- 4. .gitignore ----
$gi = Join-Path $root ".gitignore"
$want = @(
    "# --- gitsafe: 密钥与本地配置 ---",
    ".env", ".env.*", "!.env.example",
    "*.pem", "*.key", "*.p12", "*.pfx", "*.keystore", "*.jks",
    "secrets.json", "secrets.yml", "secrets.yaml",
    "credentials.json", ".npmrc", ".pypirc", ".netrc",
    "id_rsa", "id_ed25519", "id_ecdsa",
    "",
    "# --- 编辑器 / 系统 ---",
    ".vscode/", ".idea/", "*.swp", ".DS_Store", "Thumbs.db",
    "",
    "# --- 依赖与产物 ---",
    "node_modules/", "dist/", "build/", "__pycache__/", "*.pyc",
    ".venv/", "venv/", "env/", "*.log"
)

if (-not (Test-Path $gi)) {
    [System.IO.File]::WriteAllText($gi, (($want -join "`n") + "`n"), (New-Object System.Text.UTF8Encoding $false))
    Say "[OK] 已创建 .gitignore" "Green"
}
else {
    $cur = Get-Content $gi -Raw
    $existing = @()
    foreach ($ln in ($cur -split "`r?`n")) { $existing += $ln.Trim() }

    $missing = @()
    foreach ($w in $want) {
        if ([string]::IsNullOrWhiteSpace($w)) { continue }
        if ($w.StartsWith("#")) { continue }
        if ($existing -notcontains $w) { $missing += $w }
    }

    if ($missing.Count -gt 0) {
        $stamp = Get-Date -Format "yyyy-MM-dd"
        $add = "`n# --- gitsafe 追加 $stamp ---`n" + ($missing -join "`n") + "`n"
        [System.IO.File]::AppendAllText($gi, $add, (New-Object System.Text.UTF8Encoding $false))
        Say "[OK] 已向 .gitignore 追加 $($missing.Count) 条规则" "Green"
    }
    else {
        Say "[OK] .gitignore 已覆盖，无需改动" "Green"
    }
}

# ---- 5. 已被追踪的敏感文件 ----
$tracked = @(& git -C $root ls-files 2>$null)
$nameList = @(".env", ".env.local", "secrets.json", "credentials.json", "id_rsa", "id_ed25519")
$bad = @()
foreach ($f in $tracked) {
    if ([string]::IsNullOrWhiteSpace($f)) { continue }
    $b = [System.IO.Path]::GetFileName($f).ToLower()
    $isBad = $false
    if ($nameList -contains $b) { $isBad = $true }
    if ($b -match '\.(pem|p12|pfx|keystore|jks)$') { $isBad = $true }
    if ($b -match 'secret|credential') { $isBad = $true }
    if ($isBad) { $bad += $f }
}

if ($bad.Count -gt 0) {
    Say "[!] 以下文件已被 git 追踪，.gitignore 对它们无效，必须取消追踪:" "Yellow"
    foreach ($f in $bad) { Say "      $f" "Yellow" }
    Say "    执行: git rm --cached <文件>   (本地文件保留)" "Yellow"
}
else {
    Say "[OK] 没有敏感文件被追踪" "Green"
}

# ---- 6. self-test ----
Say "[i] 钩子自检..." "Cyan"
& $py $dstScanner | Out-Null
$code = $LASTEXITCODE
if ($code -eq 0) { Say "[OK] 钩子正常（暂存区干净，返回 0）" "Green" }
elseif ($code -eq 1) { Say "[OK] 钩子正常（发现风险项并拦截，返回 1）" "Green" }
else { Say "[!] 钩子返回异常码 $code" "Yellow" }

Say ""
Say "===== 安装完成 =====" "Cyan"
Say "  git commit 现在会自动扫描暂存区。"
Say "  误报跳过: git commit --no-verify"
Say "  已推到远端: 先轮换密钥，再清理历史。"